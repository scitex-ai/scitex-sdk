#!/usr/bin/env python3
"""Render an inventory document as JSON, CSV or Markdown (deterministic order)."""

from __future__ import annotations

import csv
import io
import json

COLUMNS = (
    "id",
    "kind",
    "surface",
    "path",
    "name",
    "methods",
    "view",
    "owner_package",
    "owner_kind",
    "app_module",
    "delegates_to",
    "auth",
    "permission",
    "csrf_exempt",
    "versioned",
    "contract",
    "operation_id",
    "mcp_twin",
    "namespace",
    "raw_name",
    "input",
    "python_api",
    "derived_from_operation",
    "live_status",
    "live_behaviour",
    "live_content_type",
    "violations",
    "auth_evidence",
)


def _cell(value) -> str:
    if value is None:
        return ""
    if isinstance(value, (list, tuple)):
        return ";".join(str(v) for v in value)
    if isinstance(value, bool):
        return "true" if value else "false"
    return str(value)


def flat(row: dict) -> dict:
    live = row.get("live") or {}
    merged = dict(
        row,
        live_status=live.get("status"),
        live_behaviour=live.get("behaviour"),
        live_content_type=live.get("content_type"),
    )
    return {c: _cell(merged.get(c)) for c in COLUMNS}


def _sorted(entries: list[dict]) -> list[dict]:
    return sorted(
        entries,
        key=lambda e: (e["kind"], e.get("path") or "", e.get("name") or "", e["id"]),
    )


def to_json(doc: dict) -> str:
    return json.dumps(
        dict(doc, entries=_sorted(doc["entries"])),
        indent=1,
        sort_keys=False,
        default=str,
    )


def to_csv(doc: dict) -> str:
    buf = io.StringIO()
    writer = csv.DictWriter(buf, fieldnames=COLUMNS, lineterminator="\n")
    writer.writeheader()
    for row in _sorted(doc["entries"]):
        writer.writerow(flat(row))
    return buf.getvalue()


def _table(title: str, counts: dict, label: str) -> list[str]:
    lines = [f"### {title}", "", f"| {label} | count |", "|---|---:|"]
    lines += [f"| {k} | {v} |" for k, v in counts.items()]
    return lines + [""]


def to_markdown(doc: dict, *, entries: bool = True) -> str:
    t = doc["totals"]
    lines = [
        f"# API inventory ({doc['generated_at']})",
        "",
        f"Generated by `{doc['generator']['package']} {doc['generator']['version']}` "
        f"(schema `{doc['schema']}`). Sources: `{json.dumps(doc['sources'])}`.",
        "",
        f"- programmatic entries: **{t['programmatic']}** (pages excluded: {t['pages']})",
        f"- versioned REST/ASGI: {t['versioned']} · unversioned: {t['unversioned']}",
        f"- conformant (no rule violated): {t['conformant']}",
        "",
    ]
    lines += _table("By kind", t["by_kind"], "kind")
    lines += _table("By owner kind", t["by_owner_kind"], "owner")
    lines += _table("By owner package", t["by_owner_package"], "package")
    lines += _table("By auth mode (REST/ASGI/websocket)", t["by_auth_mode"], "mode")
    rule_titles = {r["id"]: r["title"] for r in doc["rules"]}
    lines += _table(
        "By violated rule",
        {f"{k} {rule_titles.get(k, '')}": v for k, v in t["by_rule"].items()},
        "rule",
    )
    if t.get("live"):
        lines += _table("Live behaviour (anonymous GET)", t["live"], "behaviour")
    lines += [
        "### Top problem clusters",
        "",
        "| # | owner | prefix | n | rules | examples |",
        "|---|---|---|---:|---|---|",
    ]
    for i, c in enumerate(doc["clusters"], 1):
        rules = ", ".join(f"{k}×{v}" for k, v in c["rules"].items())
        ex = ", ".join(f"`{e}`" for e in c["examples"])
        lines.append(
            f"| {i} | {c['owner_package']} | `{c['prefix']}` | {c['count']} | {rules} | {ex} |"
        )
    lines += ["", "### Rules", "", "| id | title | check |", "|---|---|---|"]
    lines += [f"| {r['id']} | {r['title']} | {r['check']} |" for r in doc["rules"]]
    if doc.get("errors"):
        lines += ["", "### Errors", ""] + [f"- {e}" for e in doc["errors"]]
    if entries:
        lines += [
            "",
            "### Entries",
            "",
            "| kind | methods | path / tool | owner | auth | violations |",
            "|---|---|---|---|---|---|",
        ]
        for e in _sorted(doc["entries"]):
            if e["kind"] == "page":
                continue
            target = e.get("path") or e.get("name")
            lines.append(
                f"| {e['kind']} | {_cell(e.get('methods'))} | `{target}` | {e.get('owner_package')} "
                f"| {_cell(e.get('auth'))} | {_cell(e.get('violations'))} |"
            )
    return "\n".join(lines) + "\n"


RENDERERS = {"json": to_json, "csv": to_csv, "md": to_markdown}

__all__ = ["COLUMNS", "RENDERERS", "flat", "to_csv", "to_json", "to_markdown"]
