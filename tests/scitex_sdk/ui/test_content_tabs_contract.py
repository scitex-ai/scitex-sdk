#!/usr/bin/env python3
"""Selected-tab state contract: one visual language on every viewport.

Operator 2026-10-20 (card scholar-sdk-tabs-underline-polish-20261020),
superseding the boxed visual language of ui-tabs-selected-state-standard-20260918:
selected tab = underline ONLY in theme --accent (SciTeX navy #1a2a40 light /
gold #d4a87a dark) — no box, no surface tint, no weight change — read from
``aria-selected``; keyboard focus keeps its own ring. The a11y half of the
original contract is unchanged: responsive differences are limited to
overflow/scroll/wrapping — the selected look must not fork by viewport, so
these tests pin ``content-tabs.css`` (the shared primitive, renders anywhere)
and ``panes.css`` (phone tab bar) to the same token values, plus
source/bundle parity for the file.
"""

from __future__ import annotations

import re
from pathlib import Path

REPO = Path(__file__).resolve().parents[3]
CSS = REPO / "src/scitex_sdk/ui/static/scitex_sdk/ui/css"
CONTENT_TABS = CSS / "app/content-tabs.css"
PANES = CSS / "app/panes.css"

SELECTED = '.stx-content-tabs__tab[aria-selected="true"]'
FOCUS = ".stx-content-tabs__tab:focus-visible"
PANES_SELECTED = '.stx-panes__tab[aria-selected="true"]'
PANES_FOCUS = ".stx-panes__tab:focus-visible"


def _rule_block(css: str, selector: str) -> str:
    """Return the declaration block for an exact selector match."""
    pattern = re.compile(re.escape(selector) + r"\s*\{([^}]*)\}", re.DOTALL)
    match = pattern.search(css)
    assert match is not None, f"missing rule for {selector}"
    return match.group(1)


def test_content_tabs_source_exists():
    # Arrange
    # Act
    # Assert
    assert CONTENT_TABS.is_file(), "shared primitive stylesheet missing"


def test_content_tabs_is_in_both_bundles():
    """Source/bundle parity: app.css and all.css are generated by
    ``npx tsx css/_build-index.ts``; the new file must be imported."""
    # Arrange
    bundles = (CSS / "app.css", CSS / "all.css")
    # Act
    texts = [bundle.read_text(encoding="utf-8") for bundle in bundles]
    # Assert
    assert all('@import "./app/content-tabs.css";' in text for text in texts)


def test_selected_accent_fallback_token():
    # Arrange
    css = CONTENT_TABS.read_text(encoding="utf-8")
    # Act
    block = _rule_block(css, SELECTED)
    # Assert
    assert "var(--accent, #1a2a40)" in block  # navy light / gold dark


