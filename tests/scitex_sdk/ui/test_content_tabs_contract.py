#!/usr/bin/env python3
"""Selected-tab state contract: one visual language on every viewport.

Card ui-tabs-selected-state-standard-20260918 (operator mandate CCT 3707/3710):
selected tab = subtle surface + brand-blue text + semibold + 2px underline
indicator, read from ``aria-selected``; keyboard focus keeps its own ring.
Responsive differences are limited to overflow/scroll/wrapping — the selected
look must not fork by viewport, so these tests pin ``content-tabs.css`` (the
shared primitive, renders anywhere) and ``panes.css`` (phone tab bar) to the
same token values, plus source/bundle parity for the new file.
"""

from __future__ import annotations

import re
from pathlib import Path

REPO = Path(__file__).resolve().parents[3]
CSS = REPO / "src/scitex_sdk/ui/static/scitex_sdk/ui/css"
CONTENT_TABS = CSS / "app/content-tabs.css"
PANES = CSS / "app/panes.css"

SELECTED = '.stx-content-tabs__tab[aria-selected="true"]'
FOCUS = ".stx-content-tabs__tab:focus-visible"
PANES_SELECTED = '.stx-panes__tab[aria-selected="true"]'
PANES_FOCUS = ".stx-panes__tab:focus-visible"


def _rule_block(css: str, selector: str) -> str:
    """Return the declaration block for an exact selector match."""
    pattern = re.compile(re.escape(selector) + r"\s*\{([^}]*)\}", re.DOTALL)
    match = pattern.search(css)
    assert match is not None, f"missing rule for {selector}"
    return match.group(1)


def test_content_tabs_source_exists():
    assert CONTENT_TABS.is_file(), "shared primitive stylesheet missing"


def test_content_tabs_is_in_both_bundles():
    """Source/bundle parity: app.css and all.css are generated by
    ``npx tsx css/_build-index.ts``; the new file must be imported."""
    for bundle in (CSS / "app.css", CSS / "all.css"):
        text = bundle.read_text(encoding="utf-8")
        assert '@import "./app/content-tabs.css";' in text, bundle.name


def test_selected_reads_aria_selected_with_brand_blue_underline():
    block = _rule_block(CONTENT_TABS.read_text(encoding="utf-8"), SELECTED)
    assert "var(--text-link, #2c5d8f)" in block  # brand blue, both palettes
    assert re.search(r"color:\s*var\(--text-link", block)
    assert re.search(r"font-weight:\s*600", block)  # semibold
    assert re.search(r"box-shadow:\s*inset 0 -2px 0 var\(--text-link", block)


def test_selected_keeps_subtle_surface():
    block = _rule_block(CONTENT_TABS.read_text(encoding="utf-8"), SELECTED)
    assert re.search(r"background:\s*var\(--bg-surface", block)


def test_focus_ring_is_distinct_from_selected_indicator():
    """The focus ring must be a different token from the 2px underline and
    drawn outside the tab so the two can never overlap."""
    block = _rule_block(CONTENT_TABS.read_text(encoding="utf-8"), FOCUS)
    assert "var(--focus-ring-color" in block
    assert "var(--text-link" not in block
    assert re.search(r"outline-offset:\s*2px", block)


def test_touch_floors_and_reference_size():
    css = CONTENT_TABS.read_text(encoding="utf-8")
    base = _rule_block(css, ".stx-content-tabs__tab")
    assert re.search(r"min-height:\s*44px", base)
    assert re.search(r"min-width:\s*44px", base)
    # 13px: the operator reference both Writer and Scholar render.
    assert re.search(r"font-size:\s*13px", base)


def test_reduced_motion_is_honoured():
    css = CONTENT_TABS.read_text(encoding="utf-8")
    assert "@media (prefers-reduced-motion: reduce)" in css


def test_no_html_attributes_posing_as_css_properties():
    """Regression guard: aria-* belongs in markup, never in a declaration."""
    for path in (CONTENT_TABS, PANES):
        for lineno, line in enumerate(path.read_text(encoding="utf-8").splitlines(), 1):
            assert not re.match(r"\s*aria-[a-z-]+\s*:", line), f"{path.name}:{lineno}"


def test_panes_selected_state_matches_the_shared_contract():
    """No viewport fork: the phone tab bar reads the same tokens."""
    css = PANES.read_text(encoding="utf-8")
    selected = _rule_block(css, PANES_SELECTED)
    assert re.search(r"color:\s*var\(--text-link", selected)
    assert re.search(r"box-shadow:\s*inset 0 -2px 0 var\(--text-link", selected)
    assert re.search(r"font-weight:\s*600", selected)
    focus = _rule_block(css, PANES_FOCUS)
    assert "var(--focus-ring-color" in focus
    assert "var(--text-primary" not in focus
