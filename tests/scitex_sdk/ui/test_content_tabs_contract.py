def test_no_html_attributes_posing_as_css_properties():
    """Regression guard: aria-* belongs in markup, never in a declaration."""
    # Arrange
    paths = (CONTENT_TABS, PANES)
    # Act
    hits = [
        f"{path.name}:{lineno}"
        for path in paths
        for lineno, line in enumerate(path.read_text(encoding="utf-8").splitlines(), 1)
        if re.match(r"\s*aria-[a-z-]+\s*:", line)
    ]
    # Assert
    assert hits == []


